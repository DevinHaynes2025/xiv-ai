function pathway(storySection: string, targetModule: string, symbol: string, description: string): NeuralPathway {
  return {
    pathwayId: `${targetModule}#${symbol}`,
    storySection,
    targetModule,
    symbol,
    description,
    grantsAuthority: false,
  };
}

function zero(metric: string): VerifiedZeroCounter {
  return { metric, required: 0 };
}

function tests(suite: string, entries: ReadonlyArray<readonly [string, QueueSecurityTest['expected']]>): QueueSecurityTest[] {
  return entries.map(([attempt, expected]) => ({ suite, attempt, expected }));
}

